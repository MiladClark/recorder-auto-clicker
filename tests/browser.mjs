import assert from 'node:assert/strict';
import { mkdirSync, readdirSync, statSync } from 'node:fs';
import { resolve } from 'node:path';
import { Browser, delay, installTestSource } from './cdp.mjs';
const output = resolve('.taste-skill/functional');
mkdirSync(output, { recursive: true });
const browser = await Browser.launch();
const pass = message => console.log('PASS ' + message);
try {
  await browser.send('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: output });
  const page = await browser.newPage(process.env.TEST_URL || 'http://127.0.0.1:1420');
  await installTestSource(page);
  await page.click('Choose capture source');
  await page.wait(() => document.querySelector('.preview-topline').textContent.includes('Source connected'));
  pass('source connects to a real MediaStream preview');
  await page.click('Start recording');
  await page.wait(() => document.querySelector('.preview-topline').textContent.includes('Recording'));
  await delay(1200);
  await page.tab('Screenshot'); await page.tab('Recorder');
  assert.match(await page.eval(() => document.querySelector('.preview-topline').textContent), /Recording/);
  pass('tab changes preserve the active recording');
  await page.click('Pause'); await delay(100);
  const paused = await page.eval(() => document.querySelector('.timer').textContent);
  await delay(1200);
  assert.equal(await page.eval(() => document.querySelector('.timer').textContent), paused);
  await page.click('Resume'); await delay(1200);
  await page.click('Stop & save');
  await page.wait(() => document.querySelector('.recorder-page').textContent.includes('Recording saved.'));
  assert(await page.eval(() => window.testStreams.every(stream => stream.getTracks().every(track => track.readyState === 'ended'))));
  pass('pause excludes elapsed time; resume and stop release every source track');
  await delay(1500);
  const video = readdirSync(output).find(name => /Recording.*\.(webm|mp4)$/.test(name));
  assert(video && statSync(resolve(output, video)).size > 1000);
  pass('real MediaRecorder output downloads successfully');
  await page.screenshot(resolve(output, 'recorder-saved.png'));
  await page.eval(() => { navigator.mediaDevices.getDisplayMedia = async () => { throw new DOMException('Permission denied for test', 'NotAllowedError'); }; });
  await page.click('Choose capture source');
  assert(await page.eval(() => !document.querySelector('.recorder-page .button.primary').disabled === false));
  pass('cancelled picker leaves Start disabled and allows another attempt');
  await installTestSource(page);
  await page.click('Area');
  await page.click('Choose capture source');
  await page.wait(() => !!document.querySelector('.crop-layer.editable'));
  await page.click('Start recording');
  assert.match(await page.eval(() => document.querySelector('[role=alert]').textContent), /Draw a capture area/);
  const area = await page.eval(() => { const rect = document.querySelector('.crop-layer').getBoundingClientRect(); return { x: rect.x, y: rect.y, w: rect.width, h: rect.height }; });
  await page.send('Input.dispatchMouseEvent', { type: 'mousePressed', x: area.x + area.w * .2, y: area.y + area.h * .2, button: 'left', clickCount: 1 });
  await page.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: area.x + area.w * .8, y: area.y + area.h * .8, button: 'left', buttons: 1 });
  await page.send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: area.x + area.w * .8, y: area.y + area.h * .8, button: 'left', clickCount: 1 });
  await page.click('Start recording');
  await page.wait(() => document.querySelector('.preview-topline').textContent.includes('Recording'));
  await delay(1100); await page.click('Stop & save');
  await page.wait(() => document.querySelector('.recorder-page').textContent.includes('Recording saved.'));
  pass('region validation and actual cropped video recording');
  await page.tab('Screenshot');
  await page.eval(() => {
    const inputs = document.querySelectorAll('.screenshot-topbar .preferences-row input');
    if (inputs[0].checked) inputs[0].click();
  });
  await page.click('Capture area');
  await page.wait(() => document.querySelector('.screenshot-page canvas')?.width === 640);
  const canvas = await page.eval(() => { const rect = document.querySelector('.screenshot-page canvas').getBoundingClientRect(); return { x: rect.x, y: rect.y, w: rect.width, h: rect.height }; });
  await page.send('Input.dispatchMouseEvent', { type: 'mousePressed', x: canvas.x + canvas.w * .2, y: canvas.y + canvas.h * .2, button: 'left', clickCount: 1 });
  await page.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: canvas.x + canvas.w * .8, y: canvas.y + canvas.h * .8, buttons: 1 });
  await page.send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: canvas.x + canvas.w * .8, y: canvas.y + canvas.h * .8, button: 'left', clickCount: 1 });
  await page.click('Apply crop');
  await page.wait(() => document.querySelector('.screenshot-page canvas').width < 640);
  assert(await page.eval(() => document.querySelector('.screenshot-page canvas').width > 300));
  await page.click('Undo');
  await page.wait(() => document.querySelector('.screenshot-page canvas').width === 640);
  await page.tab('Library'); await page.tab('Screenshot');
  assert.equal(await page.eval(() => document.querySelector('.screenshot-page canvas').width), 640);
  pass('screenshot crop, save, undo and editor persistence across tabs');
  await page.screenshot(resolve(output, 'screenshot-editor.png'));
  await page.tab('Auto-clicker'); await page.click('Add item'); await page.click('Choose action button');
  await page.send('Input.dispatchKeyEvent',{type:'keyDown',key:'K',code:'KeyK',windowsVirtualKeyCode:75});
  await page.send('Input.dispatchKeyEvent',{type:'keyUp',key:'K',code:'KeyK',windowsVirtualKeyCode:75});
  await page.click('Save item'); await page.click('Start K');
  assert.match(await page.eval(() => document.querySelector('.workspace > div:not([hidden]) [role=alert]').textContent), /Windows app/);
  pass('browser preview reports native-only actions honestly');
  await page.screenshot(resolve(output, 'clicker.png'));
  for (const width of [390, 768, 1120, 1440]) {
    await page.send('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: false });
    for (const tab of ['Recorder', 'Screenshot', 'Auto-clicker', 'Library']) {
      await page.tab(tab);
      assert(await page.eval(() => document.documentElement.scrollWidth <= innerWidth && [...document.querySelectorAll('.workspace > div:not([hidden]) *')].every(node => { const rect = node.getBoundingClientRect(); return rect.width === 0 || rect.right <= innerWidth + 2; })), 'Overflow at ' + width + ' in ' + tab);
    }
  }
  pass('all four tools fit 390, 768, 1120 and 1440px without horizontal overflow');
  assert.deepEqual(page.errors, []);
  pass('no uncaught browser exceptions');
} finally { await browser.close(); }
