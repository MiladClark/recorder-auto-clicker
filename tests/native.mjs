import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Browser, delay, installTestSource } from './cdp.mjs';
const output = resolve('.taste-skill/native');
mkdirSync(output, { recursive: true });
const endpoint = process.env.WEBVIEW_DEBUG_URL || 'http://127.0.0.1:9223';
let version;
for (let attempt = 0; attempt < 30; attempt++) { try { version = await (await fetch(endpoint + '/json/version')).json(); break; } catch { await delay(300); } }
assert(version, 'The native debug endpoint did not start.');
const targets = await (await fetch(endpoint + '/json/list')).json();
const target = targets.find(target => target.title.includes('FrameCue'));
assert(target, 'Start a debug app with WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS=--remote-debugging-port=9223');
const browser = await Browser.connect(version.webSocketDebuggerUrl);
const pass = message => console.log('PASS ' + message);
try {
  const page = await browser.attach(target.id);
  assert(await page.eval(() => !!window.__TAURI_INTERNALS__));
  const invoke = (command, args = {}) => page.eval(({ command, args }) => window.__TAURI_INTERNALS__.invoke(command, args), { command, args });
  pass('native WebView2 app launches and IPC is available');
  const dirs = await invoke('get_output_dirs');
  assert(dirs.videos && dirs.pictures);
  const screenshot = await page.eval(async () => {
    const result = await window.__TAURI_INTERNALS__.invoke('capture_screen', { mode: 'fullscreen', x: null, y: null, width: null, height: null });
    return { width: result.width, height: result.height, signature: atob(result.data_url.split(',')[1]).slice(1, 4) };
  });
  assert(screenshot.width > 0 && screenshot.height > 0 && screenshot.signature === 'PNG');
  pass('real Windows GDI capture returns a valid full-desktop PNG');
  await page.eval(folder => localStorage.setItem('omnipulse.recorder.destination.v1', JSON.stringify(folder)), output);
  await page.send('Page.reload');
  await page.wait(() => !!document.querySelector('.recorder-page'));
  await installTestSource(page);
await page.click('Choose capture source');
  await page.wait(() => document.querySelector('.preview-topline').textContent.includes('Source connected'));
  await page.click('Start recording');
  await page.wait(() => document.querySelector('.preview-topline').textContent.includes('Recording'));
  await delay(1600);
  await page.tab('Screenshot'); await page.tab('Recorder');
  await page.click('Pause'); await delay(400); await page.click('Resume'); await delay(700);
  await page.click('Stop & save');
  await page.wait(() => document.querySelector('.recorder-page').textContent.includes('Recording saved.'));
  assert(!await page.eval(() => !!document.querySelector('.recorder-page [role=alert]')));
  const files = await invoke('list_recordings');
  const recorded = files.find(file => file.path.toLowerCase().includes('.taste-skill') && file.kind === 'video');
  assert(recorded && recorded.size_bytes > 1000);
  assert.equal(readFileSync(recorded.path).readUInt32BE(0), 0x1a45dfa3);
  pass('native recording encodes and streams ordered chunks to disk, then indexes the custom folder');
  await page.tab('Library');
  await page.wait(() => !!document.querySelector('.media-row'));
  await page.eval(name => [...document.querySelectorAll('.media-row')].find(row => row.textContent.includes(name)).querySelector('.button').click(), recorded.name);
  await page.wait(() => document.querySelector('.media-dialog video')?.readyState >= 1);
  assert(await page.eval(() => document.querySelector('.media-dialog video').videoWidth > 0));
  await page.screenshot(resolve(output, 'native-library-preview.png'));
  pass('asset protocol serves a real saved video to the library player');
  await page.click('Close preview', true);
  const testPng = await page.eval(() => {
    const canvas = document.createElement('canvas'); canvas.width = 160; canvas.height = 90;
    const context = canvas.getContext('2d'); context.fillStyle = '#ee696c'; context.fillRect(0, 0, 160, 90);
    return canvas.toDataURL('image/png');
  });
  const pngPath = resolve(output, 'Screenshot_native-test.png');
  await invoke('save_screenshot', { dataUrl: testPng, customPath: pngPath });
  assert.equal(readFileSync(pngPath).subarray(1, 4).toString(), 'PNG');
  const updated = await invoke('list_recordings');
  assert(updated.some(file => file.path.toLowerCase() === pngPath.toLowerCase() && file.kind === 'image'));
  pass('native screenshot writes valid PNG and the shared library indexes images');
  await page.tab('Auto-clicker');
  assert(Array.isArray(await invoke('get_clicker_items')));
  pass('multi-item clicker initializes with native IPC');
  await page.tab('Recorder');
  await page.screenshot(resolve(output, 'native-recorder.png'));
  assert.deepEqual(page.errors, []);
  writeFileSync(resolve(output, 'results.json'), JSON.stringify({ passed: true, screenshot, video: { path: recorded.path, size: recorded.size_bytes }, dirs }, null, 2));
  pass('native flow completes without uncaught WebView2 exceptions');
} finally { await browser.close(); }
